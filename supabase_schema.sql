-- 1. TABELA DE CAMPANHAS
CREATE TABLE IF NOT EXISTS campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  post_url TEXT NOT NULL,
  group_link TEXT NOT NULL,
  private_message TEXT NOT NULL,
  public_reply TEXT NOT NULL,
  keywords TEXT DEFAULT 'todos os comentários',
  status TEXT NOT NULL DEFAULT 'ativo',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABELA DE MODELOS DE MENSAGENS
CREATE TABLE IF NOT EXISTS message_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT REFERENCES campaigns(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  private_message TEXT NOT NULL,
  public_reply TEXT NOT NULL,
  is_default INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABELA DE ATENDIMENTOS (CONTACT RECORDS)
CREATE TABLE IF NOT EXISTS contact_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT REFERENCES campaigns(id) ON DELETE CASCADE,
  comment_id TEXT,
  username TEXT NOT NULL,
  internal_id TEXT,
  status TEXT NOT NULL DEFAULT 'Pendente',
  private_message_sent INTEGER DEFAULT 0,
  public_reply_sent INTEGER DEFAULT 0,
  prepared_at TIMESTAMPTZ,
  direct_confirmed_at TIMESTAMPTZ,
  public_replied_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  canceled_at TIMESTAMPTZ,
  cancel_reason TEXT,
  notes TEXT,
  tags TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABELA DE HISTÓRICO E AUDITORIA
CREATE TABLE IF NOT EXISTS interaction_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_record_id BIGINT REFERENCES contact_records(id) ON DELETE CASCADE,
  campaign_id BIGINT REFERENCES campaigns(id) ON DELETE CASCADE,
  action_type TEXT NOT NULL,
  description TEXT NOT NULL,
  previous_status TEXT,
  new_status TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABELA DE CONFIGURAÇÕES DO APLICATIVO
CREATE TABLE IF NOT EXISTS application_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. HABILITAR ROW LEVEL SECURITY (RLS) COM POLÍTICAS DE ACESSO TOTAL
ALTER TABLE campaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE interaction_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE application_settings ENABLE ROW LEVEL SECURITY;

-- Políticas de acesso livre para leitura e escrita
DROP POLICY IF EXISTS "Acesso campaigns" ON campaigns;
CREATE POLICY "Acesso campaigns" ON campaigns FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso templates" ON message_templates;
CREATE POLICY "Acesso templates" ON message_templates FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso contacts" ON contact_records;
CREATE POLICY "Acesso contacts" ON contact_records FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso history" ON interaction_history;
CREATE POLICY "Acesso history" ON interaction_history FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acesso settings" ON application_settings;
CREATE POLICY "Acesso settings" ON application_settings FOR ALL USING (true) WITH CHECK (true);

